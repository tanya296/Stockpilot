-- V2: Tier 2 tables for suppliers and purchase orders.
-- Kept as a separate migration to show how schema evolves over time.

CREATE TABLE suppliers (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255) NOT NULL UNIQUE,
    contact VARCHAR(255)
);

CREATE TABLE purchase_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id  BIGINT       NOT NULL REFERENCES suppliers (id),
    -- The warehouse the goods will be received into.
    warehouse_id BIGINT       NOT NULL REFERENCES warehouses (id),
    status       VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT', 'ORDERED', 'RECEIVED', 'CANCELLED')),
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version      BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE purchase_order_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT         NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    product_id        BIGINT         NOT NULL REFERENCES products (id),
    quantity          INT            NOT NULL CHECK (quantity > 0),
    unit_cost         NUMERIC(12, 2) NOT NULL CHECK (unit_cost >= 0)
);

CREATE INDEX idx_po_status ON purchase_orders (status);
