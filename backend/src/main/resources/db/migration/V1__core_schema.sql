-- V1: Tier 1 tables. Flyway runs each V<n>__name.sql once, in order,
-- and records it in the flyway_schema_history table.
-- Never edit a migration that has already run: add a new V<n+1> file instead.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('STAFF', 'MANAGER', 'ADMIN')),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           VARCHAR(64)    NOT NULL UNIQUE,
    name          VARCHAR(255)   NOT NULL,
    category      VARCHAR(100)   NOT NULL,
    unit_price    NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    reorder_level INT            NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    created_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE warehouses (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    city VARCHAR(100) NOT NULL
);

-- One row per (product, warehouse). "version" powers optimistic locking.
-- The CHECK is the database's last line of defence: stock can never go negative,
-- even if a bug slips past the service layer.
CREATE TABLE stock_levels (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT NOT NULL REFERENCES products (id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    quantity     INT    NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    version      BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_product_warehouse UNIQUE (product_id, warehouse_id)
);

-- Append-only ledger: rows are inserted, never updated or deleted.
CREATE TABLE stock_movements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT       NOT NULL REFERENCES products (id),
    warehouse_id BIGINT       NOT NULL REFERENCES warehouses (id),
    type         VARCHAR(20)  NOT NULL,
    quantity     INT          NOT NULL CHECK (quantity > 0),
    reason       VARCHAR(255),
    created_by   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for the queries we actually run.
CREATE INDEX idx_products_category ON products (category);
CREATE INDEX idx_movements_product_created ON stock_movements (product_id, created_at);
